// ONE-OFF, run locally: build lib/suggestions/suggestion-seed.js by asking the
// model for a pool of ideas for every seed term × diet variant
// (lib/suggestions/terms.js). ~150 Haiku calls, a few pence. The generated
// file is committed; scripts/seed-suggestions.js loads it on every deploy.
//
//   node -r dotenv/config scripts/build-suggestion-seed.js            # all terms
//   node -r dotenv/config scripts/build-suggestion-seed.js --only=curry,pasta
//
// Re-running keeps existing entries in the seed file and only asks for the
// missing ones, so a failed run can be resumed.

require("dotenv").config();
const fs = require("node:fs");
const path = require("node:path");
const { client } = require("../lib/ai");
const { SEED_TERMS, SEED_DIETS } = require("../lib/suggestions/terms");
const { suggestKey, describeSignature } = require("../lib/suggestions/normalise");
const { merge, POOL_MAX } = require("../lib/suggestions/pool");
const { suggestionPrompt, parseSuggestions } = require("../lib/suggestions/prompt");
const { fullRecipePrompt, parseFullRecipe } = require("../lib/suggestions/write");

const OUT = path.join(__dirname, "..", "lib", "suggestions", "suggestion-seed.js");
const MODEL = "claude-haiku-4-5-20251001";
const PER_POOL = 12;
const WRITE_CONCURRENCY = 6;

function save(rowsIn) {
    const rows = [...rowsIn].sort((a, b) => a.key.localeCompare(b.key) || a.diets.localeCompare(b.diets));
    const body =
        `// GENERATED by scripts/build-suggestion-seed.js — do not edit by hand.\n` +
        `// ${rows.length} pools (term × diet variant), each idea carrying a full recipe; loaded by scripts/seed-suggestions.js.\n` +
        `const SUGGESTION_SEED = ${JSON.stringify(rows)};\n\nmodule.exports = { SUGGESTION_SEED };\n`;
    fs.writeFileSync(OUT, body);
    return rows;
}

function loadExisting() {
    try {
        return require(OUT).SUGGESTION_SEED;
    } catch {
        return [];
    }
}

async function recipeFor(idea, diets) {
    const message = await client.messages.create({
        model: MODEL,
        max_tokens: 2048,
        messages: [{ role: "user", content: fullRecipePrompt({ title: idea.title, ingredients: idea.ingredients, diets }) }],
    });
    return parseFullRecipe(message.content[0].text);
}

// Write every idea in a pool up as a full recipe, a few at a time. Ideas that
// already have one are skipped (resumable); a failed write is left for next run.
async function writeRecipes(row) {
    const todo = row.ideas.filter((i) => !i.recipe);
    let cursor = 0;
    let done = 0;
    await Promise.all(
        Array.from({ length: Math.min(WRITE_CONCURRENCY, todo.length) }, async () => {
            for (let i = cursor++; i < todo.length; i = cursor++) {
                try {
                    const recipe = await recipeFor(todo[i], row.diets);
                    if (recipe) {
                        todo[i].recipe = recipe;
                        done++;
                    }
                } catch (error) {
                    console.log(`\n  ${todo[i].title}: FAILED ${String(error.message).slice(0, 80)}`);
                }
            }
        }),
    );
    return { asked: todo.length, done };
}

async function ideasFor(term, diets) {
    const message = await client.messages.create({
        model: MODEL,
        max_tokens: 2048,
        messages: [{ role: "user", content: suggestionPrompt({ hint: term === "Anything" ? "" : term, diets, count: PER_POOL, avoid: [] }) }],
    });
    return parseSuggestions(message.content[0].text);
}

(async () => {
    const only = (process.argv.find((a) => a.startsWith("--only=")) ?? "").slice(7).split(",").filter(Boolean).map(suggestKey);
    const existing = loadExisting();
    const byKey = new Map(existing.map((r) => [`${r.key}|${r.diets}`, r]));
    let asked = 0;
    let usage = { input: 0, output: 0 };

    for (const term of SEED_TERMS) {
        const key = suggestKey(term === "Anything" ? "" : term);
        if (only.length && !only.includes(key)) continue;
        for (const diets of SEED_DIETS) {
            const id = `${key}|${diets}`;
            const label = `${term}${diets ? ` (${describeSignature(diets)})` : ""}`;
            let row = byKey.get(id);
            if (!row || row.ideas.length < PER_POOL) {
                process.stdout.write(`${label} … `);
                try {
                    const ideas = await ideasFor(term, diets);
                    asked++;
                    row = { key, hint: term === "Anything" ? "" : term, diets, ideas: merge(row?.ideas ?? [], ideas, POOL_MAX) };
                    byKey.set(id, row);
                    console.log(`${ideas.length} ideas`);
                } catch (error) {
                    console.log(`FAILED: ${error.message}`);
                    continue;
                }
            }
            if (row.ideas.some((i) => !i.recipe)) {
                process.stdout.write(`${label} recipes … `);
                const { asked: n, done } = await writeRecipes(row);
                asked += n;
                console.log(`${done}/${n} written`);
                // Save after every pool so a crash loses at most one pool's writes.
                save([...byKey.values()]);
            }
        }
    }

    const rows = save([...byKey.values()]);
    const written = rows.reduce((a, r) => a + r.ideas.filter((i) => i.recipe).length, 0);
    const total = rows.reduce((a, r) => a + r.ideas.length, 0);
    console.log(`\nwrote ${rows.length} pools (${written}/${total} ideas with a full recipe) to ${path.relative(process.cwd(), OUT)} (${asked} model calls this run)`);
})().catch((error) => {
    console.error(error);
    process.exit(1);
});
